const SCAN_RETRY_DELAY_SECONDS = 5;

const INTERNAL_ERROR_MESSAGES: Record<string, string> = {
  vi: 'Đã xảy ra lỗi máy chủ nội bộ',
  en: 'An internal server error occurred',
  ja: 'サーバー内部エラーが発生しました',
  de: 'Ein interner Serverfehler ist aufgetreten',
  fr: 'Une erreur interne du serveur est survenue',
  es: 'Se produjo un error interno del servidor',
  it: 'Si è verificato un errore interno del server',
  nl: 'Er is een interne serverfout opgetreden',
  pl: 'Wystąpił wewnętrzny błąd serwera',
  sv: 'Ett internt serverfel uppstod',
};

type WorkerVariables = {
  auth: AuthContext;
  requestId: string;
  internalRequestError?: boolean;
  localeContext: RequestLocaleContext;
  d1Database?: D1DatabaseBinding;
};
type WorkerApp = { Bindings: Env; Variables: WorkerVariables };

const app = new Hono<WorkerApp>();

// Correlation in logs is generated by the server; compatible response IDs remain caller-visible only.
app.use('*', async (c, next) => {
  const { requestId, responseRequestId } = createRequestCorrelation(c.req.header('X-Request-Id'));
  c.set('requestId', requestId);
  const startedAt = Date.now();
  try {
    await next();
  } finally {
    c.header('X-Request-Id', responseRequestId);
    emitRequestTelemetry(buildRequestTelemetry({
      requestId,
      method: c.req.method,
      routePath: c.req.routePath,
      registeredRoutes: telemetryRouteTemplates,
      status: c.res.status,
      durationMs: Date.now() - startedAt,
      environment: c.env.ENVIRONMENT,
      internalError: c.get('internalRequestError'),
    }));
  }
});

// Domain cutover must not extend HSTS to unaudited subdomains.
app.use('*', async (c, next) => {
  await next();
  const legacy = Object.values(DOMAIN_PROFILES).some((profile) => profile.legacy === new URL(c.req.url).origin);
  if (c.env.PUBLIC_DOMAIN_ROUTING === 'true') c.header('Strict-Transport-Security',
    legacy ? 'max-age=63072000; includeSubDomains; preload' : 'max-age=31536000');
});

// 2. Global Security Middlewares
app.use('*', secureHeaders({
  xFrameOptions: 'DENY',
  xContentTypeOptions: 'nosniff',
  referrerPolicy: 'strict-origin-when-cross-origin',
  // COOP is path-sensitive: the SPA must keep its opener for Google GIS,
  // while the middleware below restores strict isolation for API responses.
  crossOriginOpenerPolicy: false,
}));

// SEC-7: additional security headers hono's secureHeaders doesn't cover
app.use('*', async (c, next) => {
  await next();
  c.header('Strict-Transport-Security', 'max-age=63072000; includeSubDomains; preload');
  c.header('Permissions-Policy', 'camera=(self), microphone=(), geolocation=(), payment=()');
  // Google Identity Services uses a popup and needs to retain its opener
  // relationship while exchanging the signed credential. Keep API responses
  // isolated, but allow the SPA document to communicate with OAuth popups.
  c.header('Cross-Origin-Opener-Policy', c.req.path.startsWith('/api/')
    ? 'same-origin'
    : 'same-origin-allow-popups');
  c.header('X-DNS-Prefetch-Control', 'off');
  // CSP: API responses get a locked-down policy; the SPA is served from the
  // same worker so it needs the full script/style/img connect allowances.
  const isApi = c.req.path.startsWith('/api/');
  c.header('Content-Security-Policy', isApi ? apiCsp() : spaCsp());
});

// 3. Production configuration gate: fail closed with a sanitized diagnostic
// when the deployment is dangerous. Development/staging are not gated.
app.use('*', productionConfigGate);
app.use('*', publicDomainRouting);

app.use('*', cors({
  origin: (origin, c) => isTrustedOrigin(origin, c.env) ? origin : undefined,
  allowMethods: ['GET', 'POST', 'PATCH', 'PUT', 'DELETE', 'OPTIONS'],
  // The SPA sends tenant context headers on every request and idempotency
  // keys on durable commands. Include them in preflight responses for a
  // separately-hosted frontend as well as same-origin deployments.
  allowHeaders: [
    'Content-Type',
    'Authorization',
    'Accept-Language',
    'x-user-id',
    'x-household-id',
    'X-Frigo-Expected-User-Id',
    'X-Frigo-Expected-Household-Id',
    'Idempotency-Key',
    'If-Match',
    TAKOLIO_LOCALE_HEADER,
    TAKOLIO_TIMEZONE_HEADER,
    TAKOLIO_COUNTRY_HEADER,
    TAKOLIO_REQUIRED_CELL_HEADER,
    D1_BOOKMARK_HEADER,
  ],
  credentials: true,
  exposeHeaders: ['X-Request-Id'],
  maxAge: 86400,
}));

app.use('*', sovereignCellMiddleware);
app.use('*', requestLocaleAndD1SessionMiddleware);

// 4. Global Error Handler (Sanitize internal errors in production)
app.onError((err, c) => {
  // Preserve intentional Hono errors (401/403/404/409/503, etc.). Turning
  // every exception into a 500 makes clients retry the wrong class of error
  // and hides the actual auth/tenancy contract.
  if (err instanceof HTTPException) {
    return err.getResponse();
  }

  c.set('internalRequestError', true);
  console.error(
    JSON.stringify({
      level: 'error',
      requestId: c.get('requestId'),
      code: 'INTERNAL_SERVER_ERROR',
    })
  );
  const isProd = c.env.ENVIRONMENT === 'production';
  const localeCtx = c.get('localeContext');
  const errorLocale = localeCtx && localeCtx.source !== 'default' ? localeCtx.locale : 'vi';
  return c.json(
    {
      error: isProd
        ? (INTERNAL_ERROR_MESSAGES[errorLocale] ?? INTERNAL_ERROR_MESSAGES.vi)
        : (err.message || 'Internal Server Error'),
      code: 'INTERNAL_SERVER_ERROR',
      ...(isProd ? {} : { stack: err.stack }),
    },
    500
  );
});

// 5. Public observability & statutory notices/webhooks (no session auth).
