function buildTier2(
  locale: 'ja' | 'ko' | 'th' | 'zh' | 'it',
  overrides: {
    brand: Partial<SiteDictionary['brand']>;
    nav: Partial<SiteDictionary['nav']>;
    langBanner: Partial<SiteDictionary['langBanner']>;
    landing: Partial<SiteDictionary['landing']>;
    howItWorks: Partial<SiteDictionary['howItWorks']>;
    pricing: Partial<SiteDictionary['pricing']>;
    faq: Partial<SiteDictionary['faq']>;
    stories: Partial<SiteDictionary['stories']>;
    recipes: Partial<SiteDictionary['recipes']>;
    footer: Partial<SiteDictionary['footer']>;
  },
): SiteDictionary {
  return {
    ...enDictionary,
    locale,
    brand: { ...enDictionary.brand, ...overrides.brand },
    nav: { ...enDictionary.nav, ...overrides.nav },
    langBanner: { ...enDictionary.langBanner, ...overrides.langBanner },
    landing: { ...enDictionary.landing, ...overrides.landing },
    howItWorks: { ...enDictionary.howItWorks, ...overrides.howItWorks },
    pricing: { ...enDictionary.pricing, ...overrides.pricing },
    faq: { ...enDictionary.faq, ...overrides.faq },
    stories: { ...enDictionary.stories, ...overrides.stories },
    recipes: { ...enDictionary.recipes, ...overrides.recipes },
    footer: { ...enDictionary.footer, ...overrides.footer },
  };
}

