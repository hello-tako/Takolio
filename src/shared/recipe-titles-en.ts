export function resolveRecipeSlug(recipe: { slug?: string | null; title?: string | null }): string | null {
  const rawSlug = (recipe.slug ?? '').trim();
  if (rawSlug) return rawSlug;
  const rawTitle = (recipe.title ?? '').trim();
  if (!rawTitle) return null;
  const key = normalizeRecipeLookupKey(rawTitle);
  return RECIPE_SLUG_BY_NORMALIZED_VI_TITLE[key] ?? LEGACY_VI_TITLE_ALIAS_TO_SLUG[key] ?? null;
}

export function getCanonicalEnglishRecipeTitle(recipe: { slug?: string | null; title?: string | null }): string | null {
  const slug = resolveRecipeSlug(recipe);
  if (slug && RECIPE_TITLE_EN_BY_SLUG[slug]) return RECIPE_TITLE_EN_BY_SLUG[slug];
  const rawTitle = (recipe.title ?? '').trim();
  if (!rawTitle) return null;
  const titleSlug = resolveRecipeSlug({ title: rawTitle });
  return titleSlug ? RECIPE_TITLE_EN_BY_SLUG[titleSlug] ?? null : null;
}
